-- 8. CONFERÊNCIA DOS DADOS
-- ============================================================================

SELECT
    C.ID AS CLIENTE_ID,
    C.NOME,
    C.DOCUMENTO,
    CO.ID AS CONTA_ID,
    CO.NUMERO,
    TC.DESCRICAO AS TIPO_CONTA,
    CO.SALDO,
    CO.ATIVA
FROM CLIENTE C
INNER JOIN CONTA CO
    ON CO.CLIENTE_ID = C.ID
INNER JOIN TIPO_CONTA TC
    ON TC.ID = CO.TIPO_CONTA_ID
ORDER BY C.ID, CO.ID;

SELECT
    SUM(SALDO) AS TOTAL_DOS_SALDOS
FROM CONTA;

SELECT
    ID,
    CONTA_ORIGEM_ID,
    CONTA_DESTINO_ID,
    VALOR,
    DATA_TRANSFERENCIA,
    OBSERVACAO
FROM TRANSFERENCIA
ORDER BY ID;

-- ============================================================================
-- 9. CONFERÊNCIA DAS CHAVES E RELACIONAMENTOS
-- ============================================================================

SELECT
    C.CONSTRAINT_NAME,
    C.TABLE_NAME,
    CC.COLUMN_NAME,
    R.TABLE_NAME AS TABELA_REFERENCIADA
FROM USER_CONSTRAINTS C
INNER JOIN USER_CONS_COLUMNS CC
    ON CC.CONSTRAINT_NAME = C.CONSTRAINT_NAME
   AND CC.OWNER = C.OWNER
INNER JOIN USER_CONSTRAINTS R
    ON R.CONSTRAINT_NAME = C.R_CONSTRAINT_NAME
   AND R.OWNER = C.R_OWNER
WHERE C.CONSTRAINT_TYPE = 'R'
ORDER BY
    C.TABLE_NAME,
    C.CONSTRAINT_NAME,
    CC.POSITION;

