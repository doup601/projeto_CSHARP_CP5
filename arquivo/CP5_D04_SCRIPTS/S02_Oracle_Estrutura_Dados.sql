-- ============================================================================
-- 2. CLIENTE
-- ============================================================================

CREATE TABLE CLIENTE
(
    ID          NUMBER(10)
                GENERATED BY DEFAULT AS IDENTITY,

    NOME        VARCHAR2(100) NOT NULL,

    DOCUMENTO   VARCHAR2(20) NOT NULL,

    ATIVO       NUMBER(1) DEFAULT 1 NOT NULL,

    CONSTRAINT PK_CLIENTE
        PRIMARY KEY (ID),

    CONSTRAINT UQ_CLIENTE_DOCUMENTO
        UNIQUE (DOCUMENTO),

    CONSTRAINT CK_CLIENTE_ATIVO
        CHECK (ATIVO IN (0,1))
);

-- ============================================================================
-- 3. TIPO_CONTA
-- ============================================================================

CREATE TABLE TIPO_CONTA
(
    ID          NUMBER(10)
                GENERATED BY DEFAULT AS IDENTITY,

    DESCRICAO   VARCHAR2(50) NOT NULL,

    CONSTRAINT PK_TIPO_CONTA
        PRIMARY KEY (ID),

    CONSTRAINT UQ_TIPO_CONTA_DESCRICAO
        UNIQUE (DESCRICAO)
);

-- ============================================================================
-- 4. CONTA
-- ============================================================================

CREATE TABLE CONTA
(
    ID              NUMBER(10)
                    GENERATED BY DEFAULT AS IDENTITY,

    CLIENTE_ID      NUMBER(10) NOT NULL,

    TIPO_CONTA_ID   NUMBER(10) NOT NULL,

    NUMERO          VARCHAR2(20) NOT NULL,

    SALDO           NUMBER(15,2) NOT NULL,

    ATIVA           NUMBER(1) DEFAULT 1 NOT NULL,

    CONSTRAINT PK_CONTA
        PRIMARY KEY (ID),

    CONSTRAINT UQ_CONTA_NUMERO
        UNIQUE (NUMERO),

    CONSTRAINT FK_CONTA_CLIENTE
        FOREIGN KEY (CLIENTE_ID)
        REFERENCES CLIENTE(ID),

    CONSTRAINT FK_CONTA_TIPO_CONTA
        FOREIGN KEY (TIPO_CONTA_ID)
        REFERENCES TIPO_CONTA(ID),

    CONSTRAINT CK_CONTA_SALDO
        CHECK (SALDO >= 0),

    CONSTRAINT CK_CONTA_ATIVA
        CHECK (ATIVA IN (0,1))
);

-- ============================================================================
-- 5. TRANSFERENCIA
-- ============================================================================

CREATE TABLE TRANSFERENCIA
(
    ID                  NUMBER(10)
                        GENERATED BY DEFAULT AS IDENTITY,

    CONTA_ORIGEM_ID     NUMBER(10) NOT NULL,

    CONTA_DESTINO_ID    NUMBER(10) NOT NULL,

    VALOR               NUMBER(15,2) NOT NULL,

    DATA_TRANSFERENCIA  TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,

    OBSERVACAO          VARCHAR2(200),

    CONSTRAINT PK_TRANSFERENCIA
        PRIMARY KEY (ID),

    CONSTRAINT FK_TRANSF_CONTA_ORIGEM
        FOREIGN KEY (CONTA_ORIGEM_ID)
        REFERENCES CONTA(ID),

    CONSTRAINT FK_TRANSF_CONTA_DESTINO
        FOREIGN KEY (CONTA_DESTINO_ID)
        REFERENCES CONTA(ID),

    CONSTRAINT CK_TRANSFERENCIA_VALOR
        CHECK (VALOR > 0),

    CONSTRAINT CK_TRANSFERENCIA_CONTAS
        CHECK (CONTA_ORIGEM_ID <> CONTA_DESTINO_ID)
);

-- ============================================================================
-- 6. CONFERÊNCIA DA ESTRUTURA
