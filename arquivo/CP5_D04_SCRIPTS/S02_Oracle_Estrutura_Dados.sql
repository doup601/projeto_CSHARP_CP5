    SYS_CONTEXT('USERENV', 'CON_NAME') AS CONTAINER
FROM DUAL;

-- Impede execução acidental como SYS/SYSTEM.
DECLARE
    V_USER VARCHAR2(128);
BEGIN
    SELECT USER INTO V_USER FROM DUAL;

    IF UPPER(V_USER) IN ('SYS', 'SYSTEM') THEN
        RAISE_APPLICATION_ERROR(
            -20001,
            'ERRO: conecte-se ao schema do CP5. Nao execute como SYS ou SYSTEM.'
        );
    END IF;
END;
/

-- Confere os privilégios utilizados por este exercício.
DECLARE
    V_CREATE_TABLE     NUMBER;
    V_CREATE_SEQUENCE  NUMBER;
BEGIN
    SELECT COUNT(*)
      INTO V_CREATE_TABLE
      FROM SESSION_PRIVS
     WHERE PRIVILEGE = 'CREATE TABLE';

    SELECT COUNT(*)
      INTO V_CREATE_SEQUENCE
      FROM SESSION_PRIVS
     WHERE PRIVILEGE = 'CREATE SEQUENCE';

    IF V_CREATE_TABLE = 0 THEN
        RAISE_APPLICATION_ERROR(
            -20002,
            'ERRO: falta o privilegio CREATE TABLE.'
        );
    END IF;

    IF V_CREATE_SEQUENCE = 0 THEN
        RAISE_APPLICATION_ERROR(
            -20003,
            'ERRO: falta CREATE SEQUENCE. No Oracle XE 21c local validado, este privilegio foi necessario para a estrategia IDENTITY usada no material.'
        );
    END IF;
END;
/

